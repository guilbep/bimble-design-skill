// Each copied preview gets the fonts and the design system's variables, first in <head>.
const PREVIEW_HEAD = '<link rel="stylesheet" href="../../skills/bimble-design/fonts/fonts.css">'
  + '<link rel="stylesheet" href="../../ds-vars.css">';

function build({ quiet = false } = {}) {
  const log = quiet ? () => {} : (...a) => console.log(...a);
  log('Building Bimble design-system catalog → site/');
  const tokens = readTokens();
  const cards = readPreviews();

  rmSync(SITE, { recursive: true, force: true });
  mkdirSync(SITE, { recursive: true });
  for (const dir of COPY_DIRS) {
    const src = join(ROOT, dir);
    if (existsSync(src)) cpSync(src, join(SITE, dir), { recursive: true });
    else console.warn(`  ⚠ missing dir: ${dir}`);
  }
  for (const c of cards) {
    const html = readFileSync(join(ROOT, COMPONENTS, c.name, 'preview.html'), 'utf8');
    if (!/<head>/i.test(html)) throw new Error(`${c.name}/preview.html has no <head>`);
    mkdirSync(join(SITE, 'components', c.name), { recursive: true });
    writeFileSync(join(SITE, 'components', c.name, 'preview.html'), html.replace(/<head>/i, `<head>${PREVIEW_HEAD}`));
  }

  writeFileSync(join(SITE, 'ds-vars.css'), dsVarsCss(tokens));
  writeFileSync(join(SITE, 'catalog.css'), CATALOG_CSS);
  writeFileSync(join(SITE, 'index.html'), renderPage({ tokens, cards }));

  log(`  ✓ ${cards.length} component cards`);
  log('Done. Open site/index.html (or run: make dev).');
  return { cards };
}

export { ROOT, SITE, build };

// Run the build only when invoked directly (not when imported by dev.mjs).
if (process.argv[1] === fileURLToPath(import.meta.url)) build();
